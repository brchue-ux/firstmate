/**
 * Root theme. Follows the system light/dark setting and, on Android 12+,
 * the user's wallpaper colors unless [dynamicColor] is turned off.
 */
@Composable
fun AutonomyTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AutonomyTypography,
        content = content,
    )
}

/**
 * Status accents are not part of [androidx.compose.material3.ColorScheme], so they
 * are resolved here against the current light/dark setting.
 */
object AutonomyAccents {

    @Composable
    fun planning(darkTheme: Boolean = isSystemInDarkTheme()): Color =
        if (darkTheme) StatusPlanningDark else StatusPlanningLight

    @Composable
    fun inProgress(darkTheme: Boolean = isSystemInDarkTheme()): Color =
        if (darkTheme) StatusInProgressDark else StatusInProgressLight

    @Composable
    fun completed(darkTheme: Boolean = isSystemInDarkTheme()): Color =
        if (darkTheme) StatusCompletedDark else StatusCompletedLight
}
